CREATE TABLE schedules (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id BIGINT NOT NULL REFERENCES users(id),
 day_of_week SMALLINT NOT NULL CHECK(day_of_week BETWEEN 1 AND 7),
 time_slot_id BIGINT NOT NULL REFERENCES time_slots(id),
 status VARCHAR(10) NOT NULL DEFAULT 'CLOSED' CHECK(status IN ('OPEN','CLOSED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT uq_schedule_teacher_day_slot UNIQUE(teacher_id,day_of_week,time_slot_id)
);
CREATE INDEX idx_schedules_day_slot_status ON schedules(day_of_week,time_slot_id,status);
CREATE INDEX idx_schedules_teacher ON schedules(teacher_id);
