CREATE TABLE activities (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 teacher_id BIGINT NOT NULL REFERENCES users(id),
 title VARCHAR(200) NOT NULL,
 description TEXT,
 status VARCHAR(12) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','PUBLISHED','CLOSED')),
 available_at TIMESTAMPTZ,
 deadline TIMESTAMPTZ,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_activities_deadline CHECK(deadline IS NULL OR available_at IS NULL OR deadline >= available_at)
);
CREATE INDEX idx_activities_teacher_status ON activities(teacher_id,status);
