CREATE TABLE enrollments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 schedule_id BIGINT NOT NULL REFERENCES schedules(id),
 student_id BIGINT NOT NULL REFERENCES users(id),
 start_date DATE NOT NULL DEFAULT CURRENT_DATE,
 end_date DATE,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT ck_enrollments_dates CHECK(end_date IS NULL OR end_date >= start_date)
);
CREATE UNIQUE INDEX uq_enrollments_one_active_per_schedule ON enrollments(schedule_id) WHERE active = TRUE;
CREATE INDEX idx_enrollments_student_active ON enrollments(student_id,active);
