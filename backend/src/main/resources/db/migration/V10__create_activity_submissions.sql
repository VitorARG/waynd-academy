CREATE TABLE activity_submissions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 assignment_id BIGINT NOT NULL REFERENCES activity_assignments(id) ON DELETE CASCADE,
 answer TEXT,
 submitted_at TIMESTAMPTZ,
 status VARCHAR(12) NOT NULL DEFAULT 'DRAFT' CHECK(status IN ('DRAFT','SUBMITTED','GRADED')),
 feedback TEXT,
 grade NUMERIC(5,2) CHECK(grade IS NULL OR grade BETWEEN 0 AND 100),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_submissions_assignment ON activity_submissions(assignment_id);
