CREATE TABLE lessons (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL REFERENCES users(id),
 teacher_id BIGINT NOT NULL REFERENCES users(id),
 enrollment_id BIGINT REFERENCES enrollments(id),
 schedule_id BIGINT NOT NULL REFERENCES schedules(id),
 time_slot_id BIGINT NOT NULL REFERENCES time_slots(id),
 lesson_type VARCHAR(10) NOT NULL DEFAULT 'REGULAR' CHECK(lesson_type IN ('REGULAR','MAKEUP')),
 scheduled_date DATE NOT NULL,
 status VARCHAR(25) NOT NULL DEFAULT 'SCHEDULED'
   CHECK(status IN ('SCHEDULED','COMPLETED','STUDENT_ABSENT','TEACHER_ABSENT','JUSTIFIED_ABSENCE','CANCELLED')),
 makeup_eligible BOOLEAN NOT NULL DEFAULT FALSE,
 meet_url VARCHAR(1000),
 notes TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX uq_lessons_teacher_date_slot_active ON lessons(teacher_id,scheduled_date,time_slot_id) WHERE status <> 'CANCELLED';
CREATE UNIQUE INDEX uq_lessons_student_date_slot_active ON lessons(student_id,scheduled_date,time_slot_id) WHERE status <> 'CANCELLED';
CREATE INDEX idx_lessons_teacher_date ON lessons(teacher_id,scheduled_date);
CREATE INDEX idx_lessons_student_date ON lessons(student_id,scheduled_date);
