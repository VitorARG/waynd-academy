CREATE TABLE activity_assignments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 activity_id BIGINT NOT NULL REFERENCES activities(id) ON DELETE CASCADE,
 student_id BIGINT NOT NULL REFERENCES users(id),
 assigned_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 status VARCHAR(15) NOT NULL DEFAULT 'PENDING' CHECK(status IN ('PENDING','IN_PROGRESS','SUBMITTED','GRADED')),
 CONSTRAINT uq_activity_assignment UNIQUE(activity_id,student_id)
);
CREATE INDEX idx_assignments_student_status ON activity_assignments(student_id,status);
