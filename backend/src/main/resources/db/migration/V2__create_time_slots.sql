CREATE TABLE time_slots (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 start_time TIME NOT NULL,
 end_time TIME NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE,
 CONSTRAINT uq_time_slots_start_end UNIQUE(start_time,end_time),
 CONSTRAINT ck_time_slots_duration CHECK(end_time - start_time = INTERVAL '30 minutes'),
 CONSTRAINT ck_time_slots_range CHECK(start_time >= TIME '06:00'
     AND start_time <= TIME '23:00'
     AND end_time <= TIME '23:30'
     AND start_time < end_time)
);
