CREATE TABLE makeup_credits (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 student_id BIGINT NOT NULL REFERENCES users(id),
 original_lesson_id BIGINT NOT NULL UNIQUE REFERENCES lessons(id),
 replacement_lesson_id BIGINT UNIQUE REFERENCES lessons(id),
 status VARCHAR(12) NOT NULL DEFAULT 'AVAILABLE' CHECK(status IN ('AVAILABLE','SCHEDULED','COMPLETED','CANCELLED','EXPIRED')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMPTZ NOT NULL DEFAULT (CURRENT_TIMESTAMP + INTERVAL '20 days'),
 scheduled_at TIMESTAMPTZ,
 completed_at TIMESTAMPTZ,
 CONSTRAINT ck_makeup_expiry CHECK(expires_at > created_at)
);
CREATE INDEX idx_makeup_student_status_expiry ON makeup_credits(student_id,status,expires_at);
